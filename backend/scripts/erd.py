"""Print the mobile-API ERD as Mermaid, one diagram per module, from the live
SQLModel metadata (so the document cannot drift from the models).

    uv run python scripts/erd.py > ../docs/erd-mobile-api.generated.md
"""

import importlib
import inspect
import sys
from typing import Any

from sqlalchemy import Column, Table

import app.db.models  # noqa: F401 - registers every table
from app.shared.owned import OwnedRow

MODULES = [
    "profile",
    "media",
    "habits",
    "tasks",
    "fitness",
    "finance",
    "capture",
    "ai_providers",
    "stats",
    "dashboard",
    "companion",
    "social",
    "weather",
    "sync",
]
BASE = {"owner_id", "tenant_id", "created_at", "updated_at", "version", "deleted_at"}


def _type(col: Column[Any]) -> str:
    name = type(col.type).__name__.lower()
    return {
        "varchar": "string",
        "autostring": "string",
        "biginteger": "bigint",
        "largebinary": "bytes",
        "datetime": "timestamptz",
    }.get(name, name)


def tables_of(module: str) -> list[Table]:
    mod = importlib.import_module(f"app.modules.{module}.models")
    out = []
    for _, cls in inspect.getmembers(mod, inspect.isclass):
        table = getattr(cls, "__table__", None)
        if table is not None and cls.__module__ == mod.__name__:
            out.append(table)
    return sorted(out, key=lambda t: t.name)


def diagram(module: str) -> str:
    tables = tables_of(module)
    lines = ["```mermaid", "erDiagram"]
    for t in tables:
        lines.append(f"  {t.name} {{")
        for c in t.columns:
            if c.name in BASE:
                continue
            key = " PK" if c.primary_key else (" FK" if c.foreign_keys else "")
            lines.append(f"    {_type(c)} {c.name}{key}")
        lines.append("  }")
    for t in tables:
        for c in t.columns:
            if c.name in BASE:
                continue
            for fk in c.foreign_keys:
                target = fk.column.table.name
                card = "|o--o{" if c.nullable else "||--o{"
                lines.append(f'  {target} {card} {t.name} : "{c.name}"')
    lines.append("```")
    return "\n".join(lines)


def main() -> None:
    owned = sum(
        1
        for m in MODULES
        for t in tables_of(m)
        if {"owner_id", "version"} <= set(t.c.keys())
    )
    out = sys.stdout
    out.write(f"<!-- generated by backend/scripts/erd.py; {owned} owned tables -->\n")
    for m in MODULES:
        out.write(f"\n### `{m}`\n\n")
        out.write(f"{diagram(m)}\n")


if __name__ == "__main__":
    del OwnedRow
    main()
